from fastapi import HTTPException
from sqlalchemy import select
from sqlalchemy.orm import Session

from ..core.config import get_settings
from ..ingest.loader import parse_run_id
from ..models import Judgment, Notice, NoticeObservation, Run
from ..schemas import NoticeListItem, RunCounts, RunSummary


def get_run(session: Session, run_id: str) -> Run:
    """Find a canonical run id or a run by its human-facing directory name."""

    run = session.get(Run, run_id)
    if run is not None:
        return run
    prefix = f"{run_id}--"
    run = session.scalar(
        select(Run)
        .where(Run.id.like(f"{prefix}%"))
        .order_by(Run.generated_at.desc(), Run.id.desc())
    )
    if run is None:
        raise HTTPException(status_code=404, detail=f"회차를 찾을 수 없습니다: {run_id}")
    return run


def counts_for_run(run: Run) -> RunCounts:
    raw = run.counts_json if isinstance(run.counts_json, dict) else {}
    collection = raw.get("collection")
    return RunCounts(
        notices=int(raw.get("notices") or 0),
        judgments=int(raw.get("judgments") or 0),
        reviews=int(raw.get("reviews") or 0),
        collection=collection if isinstance(collection, dict) else {},
    )


def run_summary(run: Run) -> RunSummary:
    return RunSummary(
        run_id=run.id,
        window_from=run.window_from,
        window_to=run.window_to,
        timezone=run.timezone,
        generated_at=run.generated_at,
        screening_basis=run.screening_basis,
        status=run.status,
        superseded_by=run.superseded_by,
        counts=counts_for_run(run),
    )


def attachment_status(notice: Notice) -> str:
    if not notice.attachments:
        return "none"
    if any(item.origin == "manual" for item in notice.attachments):
        return "manual"
    return "g2b"


def decimal_float(value: Any) -> float | None:
    return float(value) if value is not None else None


def latest_notice_observation(notice: Notice) -> NoticeObservation | None:
    """Return the newest observation already attached to a Notice instance."""

    return max(
        notice.observations,
        key=lambda item: (item.observed_at, item.id),
        default=None,
    )


def notice_list_item(notice: Notice, run_id: str | None = None) -> NoticeListItem:
    judgment = notice.judgment
    observation = latest_notice_observation(notice)
    effective_run_id = run_id or (observation.run_id if observation is not None else None)
    if effective_run_id is None:
        # A Notice without an observation is not a valid application row, but
        # keeping the response shape deterministic is safer for legacy data.
        effective_run_id = "unknown"
    return NoticeListItem(
        id=notice.id,
        notice_key=notice.notice_key,
        run_id=effective_run_id,
        title=notice.title,
        agency=notice.agency,
        published_at=notice.published_at,
        deadline_at=notice.deadline_at,
        estimated_price=decimal_float(notice.estimated_price),
        sample_role=notice.sample_role,
        sample_stratum=notice.sample_stratum,
        collection_bucket=notice.collection_bucket,
        grade=judgment.grade if judgment else None,
        readiness=judgment.readiness if judgment else None,
        focus=judgment.primary_focus if judgment else None,
        attachment_count=len(notice.attachments),
        attachment_status=attachment_status(notice),
    )


def run_directory(run: Run) -> Path:
    parsed = parse_run_id(run.id)
    directory_name = parsed[0] if parsed else run.id.split("--", 1)[0]
    # The run id is generated by the loader.  Keep this guard even though the
    # database is local, so a malformed legacy row cannot escape data/runs.
    if Path(directory_name).name != directory_name or directory_name in {"", ".", ".."}:
        raise HTTPException(status_code=500, detail="회차 디렉토리 식별자가 올바르지 않습니다.")
    return get_settings().bidops_root / "data" / "runs" / directory_name


def load_json_file(path: Path) -> dict[str, Any] | None:
    import json

    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError):
        return None
    return value if isinstance(value, dict) else None


def warning_counts(rows: list[Any]) -> dict[str, int]:
    return dict(Counter(row.level for row in rows))
