"""맵리듀스 Pass1 partial 병합(spec M3-01 "병합 규칙", 계약 시트 10절·13절 X9·X10).

`merge_partials`는 chunk(문서) 순서의 `RfpFactsPartial` 목록을 `RfpFacts` 하나로 합친다.
LLM 호출 없이 코드만으로, 같은 입력이면 같은 출력(결정적)이다.

- 최상위 None(X9): 그 chunk는 그 항목을 모른다 — 어디에도 기여하지 않는다. 빈 리스트·None
  스칼라도 기여가 없다. 모든 partial이 모르는 객체는 빈 인스턴스, 리스트는 []. 이름 등 값을
  지어내지 않는다(`project.name`은 None으로 남는다).
- 스칼라 leaf(객체 안 str·int·float·bool·enum, 중첩 객체는 재귀): 문서 순서상 첫 non-null을
  채택하고, 채택값과 "다른" non-null 값이 있으면 필드당 `Conflict` 1개를 만든다. 문자열은
  `normalize_text` 결과로, 그 외는 `!=`로 비교한다. 근거는 값마다 그 값을 처음 낸 partial에서
  최상위 소속 객체의 `evidence` 첫 항목(비었거나 소유 객체가 없으면 생략).
- 리스트(`MERGE_RULES`): partial 순서 → 리스트 순서로 이어 붙이고 키가 같은 뒤 항목은 버린다.
  남은 항목은 통째로 둔다(항목 안 필드·내부 리스트는 합치거나 비교하지 않는다).
- `conflicts`는 출력 전용(partial에 없음), `schema_version`은 RfpFacts 기본값.

결과는 입력과 Evidence 인스턴스를 공유하지 않는다(깊은 복사) — verify가 제자리에서 고친다.
병합은 RfpFacts 스키마를 재귀로 훑어 진행하며, `MERGE_RULES`에 없는 리스트 경로가 있으면
`TypeError("no merge key for <path>")`를 낸다(스키마 변경 감지).
"""

import json
import re
import types
import unicodedata
from collections.abc import Callable, Hashable, Iterator
from enum import Enum
from typing import Any, Union, get_args, get_origin

from pydantic import BaseModel

from bid_deep_engine.analysis.schemas import Conflict, Evidence, RfpFacts, RfpFactsPartial, iter_evidence


class MergeError(ValueError):
    """병합할 partial이 없다("no partials")."""


_EVIDENCE = "evidence: concat, dedup (quote, section_id)"
_ITEM_INTERNAL = "item-internal: no merge (kept with surviving item)"
_OUTPUT = "output-only: generated by merge"
_LOCATION_METADATA = "code-owned: cleared by merge, populated from current source cache"

# RfpFacts의 모든 리스트 경로 → 규칙 이름. 경로 표기: `a.b` 객체 필드, `a[]` 리스트 항목.
MERGE_RULES: dict[str, str] = {
    "project.evidence": _EVIDENCE,
    "project.evidence[].locations": _LOCATION_METADATA,
    "schedule.evidence": _EVIDENCE,
    "schedule.evidence[].locations": _LOCATION_METADATA,
    "eligibility": "key: (code, sorted-key params JSON)",
    "eligibility[].params.item_no": _ITEM_INTERNAL,
    "eligibility[].params.industry_code": _ITEM_INTERNAL,
    "eligibility[].params.region": _ITEM_INTERNAL,
    "eligibility[].evidence.locations": _LOCATION_METADATA,
    "evaluation.quantitative": "key: normalize_text(item)",
    "evaluation.quantitative[].criteria": _ITEM_INTERNAL,
    "evaluation.quantitative[].evidence.locations": _LOCATION_METADATA,
    "evaluation.qualitative": "key: item",
    "evaluation.evidence": _EVIDENCE,
    "evaluation.evidence[].locations": _LOCATION_METADATA,
    "staffing": "key: (role, grade, location)",
    "staffing[].evidence.locations": _LOCATION_METADATA,
    "contract_terms.evidence": _EVIDENCE,
    "contract_terms.evidence[].locations": _LOCATION_METADATA,
    "commercial_sw": "key: name",
    "commercial_sw[].evidence.locations": _LOCATION_METADATA,
    "deliverables": "key: normalize_text(value)",
    "submission_docs": (
        "key: normalized (name, due, copies, stage, condition) + full non-location evidence"
    ),
    "submission_docs[].evidence.locations": _LOCATION_METADATA,
    "conflicts": _OUTPUT,
    "conflicts[].values": _OUTPUT,
    "conflicts[].evidence": _OUTPUT,
    "conflicts[].evidence[].locations": _LOCATION_METADATA,
}

_OUTPUT_FIELDS = ("conflicts",)  # RfpFacts 최상위 출력 전용 필드
_DEFAULT_FIELDS = ("schema_version",)  # RfpFacts 기본값을 쓰는 최상위 필드


def normalize_text(s: str) -> str:
    """NFC → 앞뒤 공백 제거 → 연속 공백(`\\s+`)을 " " 하나로."""
    return re.sub(r"\s+", " ", unicodedata.normalize("NFC", s).strip())


def _evidence_key(e: Evidence) -> Hashable:
    return (e.quote, e.section_id)


def _submission_doc_key(doc: Any) -> Hashable:
    """Preserve every submission condition and every non-location Evidence field.

    ``locations`` and ``location_status`` are resolver-owned metadata.  They are deliberately
    absent from the key because merge clears and recomputes them from the current source cache.
    Page/verification/repair values are not resolver locations and must not be lost by dedup.
    """
    conditions = tuple(
        None if value is None else normalize_text(value)
        for value in (doc.name, doc.due, doc.copies, doc.stage, doc.condition)
    )
    evidence = json.dumps(
        doc.evidence.model_dump(mode="json", exclude={"locations", "location_status"}),
        sort_keys=True,
        ensure_ascii=False,
        separators=(",", ":"),
    )
    return (*conditions, evidence)


def _eligibility_key(rule: Any) -> Hashable:
    params = json.dumps(rule.params.model_dump(mode="json"), sort_keys=True, ensure_ascii=False)
    return (rule.code, params)


# 이어 붙여 병합하는 리스트 경로 → 키 함수(verify 전 값 기준). 항목 내부·출력 전용 경로는 없다.
_KEYS: dict[str, Callable[[Any], Hashable]] = {
    "project.evidence": _evidence_key,
    "schedule.evidence": _evidence_key,
    "eligibility": _eligibility_key,
    "evaluation.quantitative": lambda q: normalize_text(q.item),
    "evaluation.qualitative": lambda q: q.item,
    "evaluation.evidence": _evidence_key,
    "staffing": lambda s: (s.role, s.grade, s.location),
    "contract_terms.evidence": _evidence_key,
    "commercial_sw": lambda c: c.name,
    "deliverables": normalize_text,
    "submission_docs": _submission_doc_key,
}


def merge_partials(partials: list[RfpFactsPartial]) -> RfpFacts:
    """chunk(문서) 순서의 partial을 RfpFacts로 병합한다. 빈 목록이면 `MergeError`."""
    if not partials:
        raise MergeError("no partials")
    target = RfpFacts  # 호출 시점의 모듈 속성(스키마 감지 테스트가 바꿔 끼운다)
    _check_rules(target)
    conflicts: list[Conflict] = []
    values: dict[str, Any] = {}
    for name, field in target.model_fields.items():
        if name in _OUTPUT_FIELDS or name in _DEFAULT_FIELDS:
            continue
        ann = _unwrap_optional(field.annotation)
        present = [v for p in partials if (v := getattr(p, name, None)) is not None]
        if _is_list(ann):
            values[name] = _merge_list(name, present)
        elif _is_model(ann):
            owners = [_owner_evidence(obj) for obj in present]
            values[name] = _merge_object(ann, present, owners, name, conflicts)
        else:
            values[name] = _merge_scalar(name, present, [None] * len(present), conflicts)
    result = target(**values, conflicts=conflicts)
    # locations는 LLM/chunk가 소유하지 않는다. 병합 결과에서는 명시적으로 지우고, verify 뒤
    # evidence_locations resolver가 현재 bundle/raw 캐시로 다시 채운다.
    for evidence in iter_evidence(result, include_conflicts=True):
        evidence.locations = []
        evidence.location_status = "unavailable"
    return result


def _merge_object(
    cls: type[BaseModel],
    objs: list[BaseModel],
    owners: list[list[Evidence] | None],
    path: str,
    conflicts: list[Conflict],
) -> BaseModel:
    """같은 클래스 객체들(partial 순서)을 필드 선언 순서로 병합한다. owners는 objs와 평행."""
    kwargs: dict[str, Any] = {}
    for name, field in cls.model_fields.items():
        sub_path = f"{path}.{name}"
        ann = _unwrap_optional(field.annotation)
        vals = [getattr(obj, name) for obj in objs]
        if _is_list(ann):
            kwargs[name] = _merge_list(sub_path, [v for v in vals if v is not None])
        elif _is_model(ann):
            pairs = [(v, own) for v, own in zip(vals, owners, strict=True) if v is not None]
            kwargs[name] = _merge_object(
                ann, [v for v, _ in pairs], [own for _, own in pairs], sub_path, conflicts
            )
        else:
            kwargs[name] = _merge_scalar(sub_path, vals, owners, conflicts)
    return cls(**kwargs)


def _merge_list(path: str, lists: list[list[Any]]) -> list[Any]:
    """partial 순서 → 리스트 순서로 이어 붙이고 키가 같은 뒤 항목은 버린다(항목은 통째로)."""
    key = _KEYS.get(path)
    if key is None:
        raise TypeError(f"no merge key for {path}")
    seen: set[Hashable] = set()
    out: list[Any] = []
    for items in lists:
        for item in items:
            k = key(item)
            if k in seen:
                continue
            seen.add(k)
            out.append(_copy(item))
    return out


def _merge_scalar(
    path: str,
    vals: list[Any],
    owners: list[list[Evidence] | None],
    conflicts: list[Conflict],
) -> Any:
    """첫 non-null 채택. 다른 non-null 값이 있으면 `Conflict` 1개를 conflicts에 붙인다."""
    distinct: list[tuple[Any, list[Evidence] | None]] = []
    for value, owner in zip(vals, owners, strict=True):
        if value is None:
            continue
        if any(_same(value, seen) for seen, _ in distinct):
            continue
        distinct.append((value, owner))
    if not distinct:
        return None
    if len(distinct) > 1:
        conflicts.append(
            Conflict(
                field=path,
                values=[_stringify(v) for v, _ in distinct],
                evidence=[owner[0].model_copy(deep=True) for _, owner in distinct if owner],
            )
        )
    return distinct[0][0]


def _same(a: Any, b: Any) -> bool:
    if isinstance(a, str) and isinstance(b, str):
        return normalize_text(a) == normalize_text(b)
    return a == b


def _stringify(v: Any) -> str:
    """str 원문, bool "true"/"false", int·float `str(v)`, enum `.value`."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, Enum):
        return str(v.value)
    return v if isinstance(v, str) else str(v)


def _owner_evidence(obj: BaseModel) -> list[Evidence] | None:
    """최상위 객체의 evidence 리스트(스칼라 충돌 근거 소유). 없으면 None(`system_env`)."""
    ev = getattr(obj, "evidence", None)
    return ev if isinstance(ev, list) else None


def _copy(item: Any) -> Any:
    return item.model_copy(deep=True) if isinstance(item, BaseModel) else item


def _check_rules(model: type[BaseModel]) -> None:
    for path in _list_paths(model):
        if path not in MERGE_RULES:
            raise TypeError(f"no merge key for {path}")


def _list_paths(model: type[BaseModel], prefix: str = "") -> Iterator[str]:
    """타입 주석을 재귀로 훑어 리스트 경로를 선언 순서로 낸다."""
    for name, field in model.model_fields.items():
        ann = _unwrap_optional(field.annotation)
        path = f"{prefix}{name}"
        if _is_list(ann):
            yield path
            item = _unwrap_optional(get_args(ann)[0]) if get_args(ann) else None
            if _is_model(item):
                yield from _list_paths(item, f"{path}[].")
        elif _is_model(ann):
            yield from _list_paths(ann, f"{path}.")


def _unwrap_optional(ann: Any) -> Any:
    if get_origin(ann) in (Union, types.UnionType):
        args = [a for a in get_args(ann) if a is not type(None)]
        if len(args) == 1:
            return args[0]
    return ann


def _is_list(ann: Any) -> bool:
    return get_origin(ann) is list


def _is_model(ann: Any) -> bool:
    return isinstance(ann, type) and issubclass(ann, BaseModel)
